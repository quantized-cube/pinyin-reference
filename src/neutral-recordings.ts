// Match the complete example: changing a word, reading or target must never play
// audio for the old context or a different syllable.
export function neutralRecording(example: PronunciationExample): string | undefined {
  if (!example.tokens[example.target]?.endsWith('5')) return undefined;
  return neutralRecordings.find(recording =>
    recording.text === example.text && recording.target === example.target &&
    recording.tokens.length === example.tokens.length && recording.tokens.every((token, i) => token === example.tokens[i]),
  )?.url;
}
